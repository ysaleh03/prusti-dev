/// A visitor that is called on interior mut specifications, as generated by
/// the im_model and im_spec rewriter.
///
/// TODO: is the HIR representation stable enought that this could be
/// accomplished by a nested match rather than a full visitor?
struct CollectImModelledTypes<'tcx> {
    env_query: EnvQuery<'tcx>,
    modelled_types: FxHashMap<HirId, &'tcx hir::Ty<'tcx>>,
    abstract_fields: FxHashMap<HirId, Vec<(HirId, Ty<'tcx>)>>,
    capabilities: FxHashMap<HirId, Vec<(hir::Expr<'tcx>, hir::Expr<'tcx>, hir::HirId)>>,
}

impl<'tcx> intravisit::Visitor<'tcx> for CollectImModelledTypes<'tcx> {
    type NestedFilter = prusti_rustc_interface::middle::hir::nested_filter::All;

    fn maybe_tcx(&mut self) -> Self::MaybeTyCtxt {
        self.env_query.tcx()
    }

    fn visit_item(&mut self, item: &'tcx hir::Item<'tcx>) {
        if let hir::ItemKind::Impl(_impl) = &item.kind {
            let impl_id = _impl.self_ty.hir_id;
            let attrs = self.env_query.get_local_attributes(item.hir_id());

            if has_im_model_impl_attr(attrs) {
                println!("{} is im_model", impl_id);

                self.modelled_types.insert(impl_id, _impl.self_ty);

                // let tyck_res = self.env_query.tcx().typeck(impl_id.owner.def_id);
                // let substs = tyck_res.node_args(impl_id);
                // TODO: rust seems to be unable to typecheck the given struct.

                for item_id in _impl.items {
                    let item_attrs = self.env_query.get_local_attributes(item_id.hir_id());
                    if has_im_model_field_attr(item_attrs) {
                        let item_hir_id = item_id.hir_id();
                        let field_ty = self
                            .env_query
                            .tcx()
                            .fn_sig(item_hir_id.owner.def_id)
                            .instantiate_identity()
                            .output()
                            .skip_binder();
                        // println!("found field {}: {field_ty}", item_id.hir_id());
                        self.abstract_fields
                            .entry(impl_id)
                            .and_modify(|v| v.push((item_hir_id, field_ty)))
                            .or_insert(vec![(item_hir_id, field_ty)]);
                    }
                }
            }

            if has_im_spec_impl_attr(attrs) {
                // println!("{impl_id} is im_spec");
            }
        }

        intravisit::walk_item(self, item);
    }
}
